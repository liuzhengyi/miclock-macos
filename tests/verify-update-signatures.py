#!/usr/bin/env python3
"""Verify Sparkle archive + signed feed with the public key only.

Never reads Keychain/private-key files, never downloads or installs an update.
Signature length covers the exact feed byte prefix as generated by Sparkle.
"""
import argparse
import base64
import json
import plistlib
import re
from pathlib import Path
from urllib.parse import urlparse
from xml.etree import ElementTree

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey


def verify_feed(data: bytes, public_key: Ed25519PublicKey) -> None:
    matches = list(re.finditer(
        rb"<!-- sparkle-signatures:\s*edSignature:\s*([A-Za-z0-9+/=]+)\s*length:\s*([0-9]+)\s*-->", data
    ))
    if len(matches) != 1:
        raise ValueError("exactly one Sparkle signature trailer is required")
    signature = matches[0]
    length = int(signature.group(2))
    if length != signature.start() or data[signature.end():].strip():
        raise ValueError("unsigned content before/after the trailer is not allowed")
    decoded = base64.b64decode(signature.group(1), validate=True)
    if len(decoded) != 64:
        raise ValueError("Ed25519 signature must be 64 bytes")
    public_key.verify(decoded, data[:length])


def verify(feed_path: Path, archive_path: Path, info_path: Path) -> dict:
    info = plistlib.loads(info_path.read_bytes())
    key = Ed25519PublicKey.from_public_bytes(base64.b64decode(info["SUPublicEDKey"], validate=True))
    feed = feed_path.read_bytes()
    verify_feed(feed, key)
    root = ElementTree.fromstring(feed)
    ns = {"sparkle": "http://www.andymatuschak.org/xml-namespaces/sparkle"}
    matching = [item for item in root.findall("channel/item") if
                item.findtext("sparkle:version", namespaces=ns) == str(info["CFBundleVersion"])]
    if len(matching) != 1:
        raise ValueError("current build must occur exactly once in the feed")
    item = matching[0]
    if item.findtext("sparkle:shortVersionString", namespaces=ns) != info["CFBundleShortVersionString"]:
        raise ValueError("feed short version does not match Info.plist")
    if item.findtext("sparkle:minimumSystemVersion", namespaces=ns) != info["LSMinimumSystemVersion"]:
        raise ValueError("feed minimum system version does not match Info.plist")
    enclosure = item.find("enclosure")
    if enclosure is None:
        raise ValueError("current feed item lacks an update archive")
    url = urlparse(enclosure.attrib["url"])
    expected = f'/app/app_17ftjhzb3vs/downloads/MicLock-{info["CFBundleShortVersionString"]}.dmg'
    if url.scheme != "https" or url.netloc != "ecnkfnba0c1r.feishuapp.com" or url.path != expected or url.query or url.fragment:
        raise ValueError("archive URL does not match the trusted canonical download")
    archive = archive_path.read_bytes()
    if len(archive) != int(enclosure.attrib["length"]):
        raise ValueError("archive byte length does not match signed enclosure")
    signature = base64.b64decode(enclosure.attrib[f'{{{ns["sparkle"]}}}edSignature'], validate=True)
    if len(signature) != 64:
        raise ValueError("archive Ed25519 signature must be 64 bytes")
    key.verify(signature, archive)

    # Negative checks prevent a verifier accidentally accepting metadata while
    # ignoring the actual archive/feed byte integrity.
    altered = bytes([archive[0] ^ 1]) + archive[1:]
    try:
        key.verify(signature, altered)
    except InvalidSignature:
        archive_tamper_rejected = True
    else:
        raise ValueError("tampered archive unexpectedly verified")
    altered_feed = bytes([feed[0] ^ 1]) + feed[1:]
    try:
        verify_feed(altered_feed, key)
    except InvalidSignature:
        feed_tamper_rejected = True
    else:
        raise ValueError("tampered feed unexpectedly verified")
    wrong_bytes = bytearray(base64.b64decode(info["SUPublicEDKey"], validate=True))
    wrong_bytes[0] ^= 1
    wrong_key = Ed25519PublicKey.from_public_bytes(bytes(wrong_bytes))
    try:
        wrong_key.verify(signature, archive)
    except InvalidSignature:
        archive_wrong_key_rejected = True
    else:
        raise ValueError("archive accepted a different public key")
    try:
        verify_feed(feed, wrong_key)
    except InvalidSignature:
        feed_wrong_key_rejected = True
    else:
        raise ValueError("feed accepted a different public key")
    return {"status": "pass", "version": info["CFBundleShortVersionString"], "build": str(info["CFBundleVersion"]),
            "feedSignatureVerified": True, "archiveSignatureVerified": True,
            "archiveTamperRejected": archive_tamper_rejected, "feedTamperRejected": feed_tamper_rejected,
            "archiveWrongKeyRejected": archive_wrong_key_rejected, "feedWrongKeyRejected": feed_wrong_key_rejected,
            "usesPublicKeyOnly": True, "downloadsOrInstalls": False}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--feed", type=Path, default=Path(__file__).resolve().parents[1] / "release/appcast.xml")
    parser.add_argument("--archive", type=Path, default=Path(__file__).resolve().parents[1] / "release/MicLock-3.2.0.dmg")
    parser.add_argument("--info", type=Path, default=Path(__file__).resolve().parents[1] / "menu-app/Info.plist")
    args = parser.parse_args()
    print(json.dumps(verify(args.feed, args.archive, args.info), ensure_ascii=False, indent=2))
